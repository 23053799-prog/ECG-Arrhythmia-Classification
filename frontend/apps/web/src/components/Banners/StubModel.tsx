import { AlertCircle } from "lucide-react"
import { useHealth } from "../../hooks/useHealth"

export function StubModel() {
  const { data } = useHealth()

  if (data?.model?.is_stub !== true) {
    return null
  }

  return (
    <div
      role="alert"
      className="flex items-center gap-3 border-b border-amber-300
      bg-amber-50 px-5 py-3 text-sm text-amber-950"
    >
      <AlertCircle size={19} className="shrink-0" />

      <p>
        <strong>STUB MODEL: results are fake.</strong> These results are
        generated by a placeholder model and must not be treated as
        meaningful model predictions.
      </p>
    </div>
  )
}